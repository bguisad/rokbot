package dev.rokbot.nativeapp;

import android.content.Context;
import android.content.pm.PackageInfo;
import android.os.Build;
import org.json.JSONObject;
import java.io.ByteArrayOutputStream;
import java.io.File;
import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.io.InputStream;
import java.nio.ByteBuffer;
import java.nio.ByteOrder;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;

public class HermesPatcher {
    private static volatile boolean sAppliedUnpairedBundle = false;

    public static boolean hasAppliedUnpairedBundle() {
        return sAppliedUnpairedBundle;
    }

    public static void markAppliedUnpairedBundle(boolean applied) {
        sAppliedUnpairedBundle = applied;
    }

    public static boolean hasUnpairedBundle(Context context) {
        if (context == null) return false;
        try (InputStream ignored = context.getAssets().open("recipes/unpaired.hbc")) {
            return true;
        } catch (Throwable t) {
            return false;
        }
    }

    public static File ensureUnpairedBundleFile(Context context) {
        if (context == null || !hasUnpairedBundle(context)) return null;
        try {
            File outDir = new File(context.getFilesDir(), "RokBotUnpaired");
            File outFile = ensureUnpairedBundle(outDir, installStamp(context), () -> {
                try (InputStream is = context.getAssets().open("recipes/unpaired.hbc")) {
                    return readAllBytes(is);
                }
            });
            sAppliedUnpairedBundle = outFile.exists() && outFile.length() > 0;
            return outFile;
        } catch (Throwable t) {
            File stale = new File(new File(context.getFilesDir(), "RokBotUnpaired"), "unpaired.hbc");
            return stale.exists() && stale.length() > 0 ? stale : null;
        }
    }

    interface BytesSource {
        byte[] read() throws Exception;
    }

    static final String UNPAIRED_STAMP_FILE = "unpaired.stamp";

    /**
     * Copies unpaired.hbc out of the APK unless the copy on disk was made by this very install.
     * An in-place upgrade (adb install -r, the in-app updater, a sideloaded APK) keeps files/,
     * so without the stamp the previous build's bundle would keep running.
     */
    static File ensureUnpairedBundle(File outDir, String stamp, BytesSource source) throws Exception {
        outDir.mkdirs();
        File outFile = new File(outDir, "unpaired.hbc");
        File stampFile = new File(outDir, UNPAIRED_STAMP_FILE);
        if (isBundleCurrent(outFile, stampFile, stamp)) return outFile;
        writeAtomically(outFile, source.read());
        writeAtomically(stampFile, stamp.getBytes(StandardCharsets.UTF_8));
        return outFile;
    }

    // ---- staleness of bundles generated into files/ ----

    private static volatile String sInstallStamp;

    /**
     * Fingerprint of the bundle inputs this APK ships: gateway-template.hbc's SHA-256 (from
     * gateway-template.json), the installed versionCode and the install's lastUpdateTime. Any
     * reinstall or upgrade changes it, so bundles generated by an older build are regenerated on
     * the next launch while the pairing itself (Storage prefs) is left alone.
     */
    static String installStamp(Context context) {
        String cached = sInstallStamp;
        if (cached != null) return cached;
        String templateSha = "";
        try (InputStream is = context.getAssets().open("recipes/gateway-template.json")) {
            templateSha = new JSONObject(new String(readAllBytes(is), StandardCharsets.UTF_8)).optString("templateSha256", "");
        } catch (Throwable ignored) {}
        long versionCode = -1L;
        long lastUpdateTime = -1L;
        try {
            PackageInfo pi = context.getPackageManager().getPackageInfo(context.getPackageName(), 0);
            versionCode = Build.VERSION.SDK_INT >= 28 ? pi.getLongVersionCode() : pi.versionCode;
            lastUpdateTime = pi.lastUpdateTime;
        } catch (Throwable ignored) {}
        String stamp = bundleStamp(templateSha, versionCode, lastUpdateTime);
        sInstallStamp = stamp;
        return stamp;
    }

    static String bundleStamp(String templateSha256, long versionCode, long lastUpdateTime) {
        String sha = templateSha256 == null ? "" : templateSha256.trim().toLowerCase(java.util.Locale.ROOT);
        return "template=" + sha + "\napk=" + versionCode + "@" + lastUpdateTime;
    }

    /** Contents of RokBotPaired/.bundle-meta; builds before rokbot.2 wrote only url + "\n" + token. */
    static String pairedBundleMeta(String url, String token, String stamp) {
        return url + "\n" + token + "\n" + stamp;
    }

    static boolean isBundleCurrent(File bundle, File metaFile, String expectedMeta) {
        if (bundle == null || metaFile == null || expectedMeta == null) return false;
        if (!bundle.isFile() || bundle.length() == 0 || !metaFile.isFile()) return false;
        try (FileInputStream fis = new FileInputStream(metaFile)) {
            return expectedMeta.equals(new String(readAllBytes(fis), StandardCharsets.UTF_8));
        } catch (Throwable t) {
            return false;
        }
    }

    static void writeAtomically(File outFile, byte[] bytes) throws Exception {
        File tmpFile = new File(outFile.getParentFile(), outFile.getName() + ".tmp");
        try (FileOutputStream fos = new FileOutputStream(tmpFile)) {
            fos.write(bytes);
            fos.getFD().sync();
        }
        if (!tmpFile.renameTo(outFile)) {
            try (FileOutputStream fos = new FileOutputStream(outFile)) {
                fos.write(bytes);
                fos.getFD().sync();
            }
            tmpFile.delete();
        }
    }

    public static boolean hasGatewayTemplate(Context context) {
        try (InputStream ignored = context.getAssets().open("recipes/gateway-template.json");
             InputStream ignored2 = context.getAssets().open("recipes/gateway-template.hbc")) {
            return true;
        } catch (Throwable t) {
            return false;
        }
    }

    public static File generatePairedBundle(Context context, String url, String token) throws Exception {
        byte[] jsonBytes;
        try (InputStream is = context.getAssets().open("recipes/gateway-template.json")) {
            jsonBytes = readAllBytes(is);
        }
        JSONObject meta = new JSONObject(new String(jsonBytes, StandardCharsets.UTF_8));

        byte[] bundle;
        try (InputStream is = context.getAssets().open("recipes/gateway-template.hbc")) {
            bundle = readAllBytes(is);
        }

        String expectedSha = meta.optString("templateSha256", "");
        if (!expectedSha.isEmpty() && !sha256Hex(bundle).equalsIgnoreCase(expectedSha)) {
            throw new IllegalStateException("gateway-template.hbc SHA-256 verification failed");
        }

        JSONObject opcodes = meta.getJSONObject("opcodes");
        JSONObject strings = meta.getJSONObject("strings");
        int emptyString = meta.getInt("emptyString");
        int urlKey = meta.getInt("urlKey");
        int tokenKey = meta.getInt("tokenKey");
        int bodyOffset = meta.getInt("bodyOffset");
        int bodyCapacity = meta.getInt("bodyCapacity");
        int bodyLengthOffset = meta.getInt("bodyLengthOffset");

        if (bodyOffset < 0 || bodyCapacity <= 0 || bodyOffset + bodyCapacity > bundle.length - 20) {
            throw new IllegalStateException("Invalid Hermes template body bounds");
        }

        ByteBuffer body = ByteBuffer.allocate(bodyCapacity).order(ByteOrder.LITTLE_ENDIAN);

        // Op: NewObject reg 0
        body.put((byte) opcodes.getInt("NewObject"));
        body.put((byte) 0);

        String[] values = new String[] { url, token };
        int[] keys = new int[] { urlKey, tokenKey };

        for (int cache = 0; cache < 2; cache++) {
            loadString(body, opcodes, 1, emptyString);
            String val = values[cache];
            for (int i = 0; i < val.length(); i++) {
                char c = val.charAt(i);
                if (c < 33 || c > 126) {
                    throw new IllegalArgumentException("URL and token must be printable ASCII");
                }
                String code = String.valueOf((int) c);
                if (strings.has(code)) {
                    loadString(body, opcodes, 2, strings.getInt(code));
                } else if (c >= '0' && c <= '9') {
                    body.put((byte) opcodes.getInt("LoadConstUInt8"));
                    body.put((byte) 2);
                    body.put((byte) (c - '0'));
                } else {
                    throw new IllegalArgumentException("Unsupported char in url/token: " + c);
                }
                body.put((byte) opcodes.getInt("Add"));
                body.put((byte) 1);
                body.put((byte) 1);
                body.put((byte) 2);
            }
            int keyIdx = keys[cache];
            if (keyIdx < 65536) {
                body.put((byte) opcodes.getInt("DefineOwnById"));
                body.put((byte) 0);
                body.put((byte) 1);
                body.put((byte) cache);
                body.putShort((short) keyIdx);
            } else {
                body.put((byte) opcodes.getInt("DefineOwnByIdLong"));
                body.put((byte) 0);
                body.put((byte) 1);
                body.put((byte) cache);
                body.putInt(keyIdx);
            }
        }

        body.put((byte) opcodes.getInt("Ret"));
        body.put((byte) 0);

        int bodyLen = body.position();
        byte[] bodyBytes = body.array();

        System.arraycopy(bodyBytes, 0, bundle, bodyOffset, bodyLen);
        for (int i = bodyOffset + bodyLen; i < bodyOffset + bodyCapacity; i++) {
            bundle[i] = 0;
        }

        ByteBuffer.wrap(bundle, bodyLengthOffset, 4).order(ByteOrder.LITTLE_ENDIAN).putInt(bodyLen);

        // Session list arrangement (hermes-settings.mjs listSortEdits): verified in-place edits that
        // are always part of the paired bundle; the RN bell switches between the official list and
        // the grouped one in place (no bundle change, no React Native reload).
        if (applyListArrangement(bundle, meta.optJSONObject("listSort"), ListArrangement.titleLanguage(context)) == LIST_SORT_NONE) {
            android.util.Log.w("RokBotHermes", "list arrangement edits unavailable; official list only");
        }

        MessageDigest sha1 = MessageDigest.getInstance("SHA-1");
        sha1.update(bundle, 0, bundle.length - 20);
        byte[] digest = sha1.digest();
        System.arraycopy(digest, 0, bundle, bundle.length - 20, 20);

        File outDir = new File(context.getFilesDir(), "RokBotPaired");
        outDir.mkdirs();
        File outFile = new File(outDir, "index.android.bundle");
        writeAtomically(outFile, bundle);
        return outFile;
    }

    /** True when gateway-template.json carries the live list arrangement (rokbot.5b+ builds). */
    static boolean hasListSort(Context context) {
        try (InputStream is = context.getAssets().open("recipes/gateway-template.json")) {
            JSONObject meta = new JSONObject(new String(readAllBytes(is), StandardCharsets.UTF_8));
            return isLiveListSort(meta.optJSONObject("listSort"));
        } catch (Throwable t) {
            return false;
        }
    }

    static boolean isLiveListSort(JSONObject sort) {
        return sort != null && sort.optInt("live", 0) == 1 && sort.optJSONArray("edits") != null
                && sort.optJSONArray("edits").length() > 0 && sort.optJSONObject("titles") != null;
    }

    static final int LIST_SORT_NONE = 0;
    static final int LIST_SORT_LIVE = 3;

    /**
     * Applies the live list arrangement published in gateway-template.json "listSort":
     * {"live":1, "edits":[...], "titles":{"zh":[...], "en":[...]}}. The edits and one titles set
     * go in together (all anchors checked first, nothing written otherwise). Returns
     * LIST_SORT_LIVE or LIST_SORT_NONE. The caller recomputes the footer SHA-1.
     */
    static int applyListArrangement(byte[] bundle, JSONObject listSort, String titleLanguage) {
        if (bundle == null || !isLiveListSort(listSort)) return LIST_SORT_NONE;
        JSONObject titles = listSort.optJSONObject("titles");
        Edit[] named = parseEdits(titles.optJSONArray(titles.has(titleLanguage) ? titleLanguage : "en"));
        return applyEditLists(bundle, parseEdits(listSort.optJSONArray("edits")), named) ? LIST_SORT_LIVE : LIST_SORT_NONE;
    }

    /** One verified in-place edit: `original` must be at `offset`, `patched` (same length) replaces it. */
    static final class Edit {
        final int offset;
        final byte[] original;
        final byte[] patched;

        Edit(int offset, byte[] original, byte[] patched) {
            this.offset = offset;
            this.original = original;
            this.patched = patched;
        }
    }

    /** [{offset, original, patched}] (hex) -> edits; null when missing, empty or malformed. */
    static Edit[] parseEdits(org.json.JSONArray edits) {
        if (edits == null || edits.length() == 0) return null;
        Edit[] out = new Edit[edits.length()];
        for (int i = 0; i < out.length; i++) {
            JSONObject e = edits.optJSONObject(i);
            if (e == null) return null;
            byte[] orig = hexToBytes(e.optString("original", ""));
            byte[] next = hexToBytes(e.optString("patched", ""));
            if (orig == null || next == null) return null;
            out[i] = new Edit(e.optInt("offset", -1), orig, next);
        }
        return out;
    }

    /**
     * Applies edit lists in place after checking every original byte first; nothing is written
     * unless every list is present, all anchors match, no two edits overlap and none touches the
     * footer. Mirrors applyListSortEdits in android/patchers/hermes-settings.mjs.
     */
    static boolean applyEditLists(byte[] bundle, Edit[]... lists) {
        if (bundle == null || lists == null || lists.length == 0) return false;
        java.util.List<Edit> all = new java.util.ArrayList<>();
        for (Edit[] list : lists) {
            if (list == null || list.length == 0) return false;
            for (Edit e : list) {
                if (e == null || e.offset < 0 || e.original == null || e.patched == null || e.original.length == 0
                        || e.original.length != e.patched.length || (long) e.offset + e.original.length > bundle.length - 20) {
                    return false;
                }
                for (int j = 0; j < e.original.length; j++) {
                    if (bundle[e.offset + j] != e.original[j]) return false;
                }
                for (Edit o : all) {
                    if (e.offset < o.offset + o.original.length && o.offset < e.offset + e.original.length) return false;
                }
                all.add(e);
            }
        }
        for (Edit e : all) System.arraycopy(e.patched, 0, bundle, e.offset, e.patched.length);
        return true;
    }

    /**
     * Extra .bundle-meta line: the live list arrangement and its title language are part of the
     * paired bundle (a language change regenerates it; the bell itself never does).
     */
    static String listSortMeta(Context context) {
        return "\nlistSort=live:" + ListArrangement.titleLanguage(context);
    }

    static byte[] hexToBytes(String hex) {
        if (hex == null || (hex.length() & 1) != 0) return null;
        byte[] out = new byte[hex.length() / 2];
        for (int i = 0; i < out.length; i++) {
            int hi = Character.digit(hex.charAt(2 * i), 16);
            int lo = Character.digit(hex.charAt(2 * i + 1), 16);
            if (hi < 0 || lo < 0) return null;
            out[i] = (byte) ((hi << 4) | lo);
        }
        return out;
    }

    private static void loadString(ByteBuffer buf, JSONObject opcodes, int reg, int idx) throws Exception {
        if (idx < 65536) {
            buf.put((byte) opcodes.getInt("LoadConstString"));
            buf.put((byte) reg);
            buf.putShort((short) idx);
        } else {
            buf.put((byte) opcodes.getInt("LoadConstStringLongIndex"));
            buf.put((byte) reg);
            buf.putInt(idx);
        }
    }

    private static String sha256Hex(byte[] bytes) throws Exception {
        byte[] digest = MessageDigest.getInstance("SHA-256").digest(bytes);
        StringBuilder sb = new StringBuilder(digest.length * 2);
        for (byte b : digest) sb.append(String.format("%02x", b & 0xff));
        return sb.toString();
    }

    private static byte[] readAllBytes(InputStream is) throws Exception {
        ByteArrayOutputStream baos = new ByteArrayOutputStream();
        byte[] buf = new byte[8192];
        int n;
        while ((n = is.read(buf)) != -1) {
            baos.write(buf, 0, n);
        }
        return baos.toByteArray();
    }
}
