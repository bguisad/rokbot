#!/usr/bin/env python3
"""Hermes Bytecode (HBC v98) synthesizer and Expo Updates suppressor."""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import sys

SCRIPT_DIR = Path(__file__).resolve().parent
RECIPES_DIR = SCRIPT_DIR.parent / "recipes"

def patch_hermes_bytecode(template_hbc: bytes, meta: dict, url: str, token: str = "") -> bytes:
    opcodes = meta['opcodes']
    strings = meta['strings']
    empty_str = meta['emptyString']
    keys = [meta['urlKey'], meta['tokenKey']]
    values = [url, token]
    body_offset = meta['bodyOffset']
    body_capacity = meta['bodyCapacity']
    body_length_offset = meta['bodyLengthOffset']

    body = bytearray()

    def op(name): body.append(opcodes[name])
    def u8(n): body.append(n & 0xff)
    def u16(n): body.extend(struct.pack('<H', n))
    def u32(n): body.extend(struct.pack('<I', n))

    def load_str(reg, idx):
        if idx < 65536:
            op('LoadConstString'); u8(reg); u16(idx)
        else:
            op('LoadConstStringLongIndex'); u8(reg); u32(idx)

    # NewObject reg 0
    op('NewObject'); u8(0)

    for cache, (val, key_idx) in enumerate(zip(values, keys)):
        load_str(1, empty_str)
        for c in val:
            code = str(ord(c))
            if code in strings:
                load_str(2, strings[code])
            elif '0' <= c <= '9':
                op('LoadConstUInt8'); u8(2); u8(ord(c) - ord('0'))
            else:
                raise ValueError(f'Unsupported character in connection config: {c}')
            op('Add'); u8(1); u8(1); u8(2)

        if key_idx < 65536:
            op('DefineOwnById'); u8(0); u8(1); u8(cache); u16(key_idx)
        else:
            op('DefineOwnByIdLong'); u8(0); u8(1); u8(cache); u32(key_idx)

    # Ret reg 0
    op('Ret'); u8(0)

    if len(body) > body_capacity:
        raise ValueError(f'Generated bytecode length ({len(body)}) exceeds capacity ({body_capacity})')

    bundle = bytearray(template_hbc)
    bundle[body_offset:body_offset + len(body)] = body
    bundle[body_offset + len(body):body_offset + body_capacity] = bytes(body_capacity - len(body))

    # Update body length (uint32 LE)
    struct.pack_into('<I', bundle, body_length_offset, len(body))

    # Recalculate trailing SHA-1
    footer = hashlib.sha1(bundle[:-20]).digest()
    bundle[-20:] = footer

    return bytes(bundle)

def main():
    parser = argparse.ArgumentParser(description="Patch Hermes bytecode bundle")
    parser.add_argument("--bundle", type=Path, required=True, help="Path to index.android.bundle")
    parser.add_argument("--manifest-pin", type=Path, help="Path to manifest.json pinning file")
    parser.add_argument("--host", type=str, help="Pre-configured Host address")
    parser.add_argument("--pairing-code", type=str, default="", help="Pre-configured pairing code")
    args = parser.parse_args()

    meta_file = RECIPES_DIR / "gateway-template.json"
    if not meta_file.exists():
        raise FileNotFoundError(f"Missing {meta_file}")
    meta = json.loads(meta_file.read_text(encoding="utf-8"))

    if args.host:
        content = args.bundle.read_bytes()
        patched = patch_hermes_bytecode(content, meta, args.host, args.pairing_code)
        args.bundle.write_bytes(patched)
        print(f"Patched Hermes bytecode written to {args.bundle}")
    else:
        print("No host specified, leaving bundle in dynamic pairing mode")

if __name__ == "__main__":
    main()
